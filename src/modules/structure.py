def _metadata_only_modification(flags: list[Flag], pdf_path: str) -> list[Flag]:
    """Downgrade META_DOCUMENT_MODIFIED to "low" when the modification is provably invisible.

    "Modified 104 days after creation" is suspicious when it means the pages
    were edited. When the original revision was itself unmodified
    (original_revision_unmodified) and every later revision renders exactly
    like it (visible_content_unchanged), the modification only touched
    metadata or attachments. A NEW Flag is built: module results are shown
    verbatim in the per-module breakdown.

    Example:
        Intarsys ZUGFeRD sample, ModDate 104 days after CreationDate, Factur-X
        XML attached in an incremental update -> severity "low".
    """
    out = []
    for f in flags:
        if (f.code == "META_DOCUMENT_MODIFIED" and f.severity != "low"
                and original_revision_unmodified(pdf_path)
                and visible_content_unchanged(pdf_path) is True):
            details = dict(f.details or {})
            details["visible_content_changed"] = False
            f = Flag(severity="low", code=f.code,
                     message=f.message + " (metadata or attachments only: every "
                                         "page renders exactly like the original)",
                     details=details)
        out.append(f)
    return out


def analyze_structure(pdf_data: PDFData, verify_signatures: bool = True) -> ModuleResult:
    """
    Analyze PDF internal structure for signs of manipulation.

    Args:
        pdf_data: Extracted PDF data
        verify_signatures: Whether to verify digital signatures via EU DSS API
                          (requires internet, set False for offline use)

    Returns:
        ModuleResult with score, flags, and confidence
    """
    all_flags = []

    # First, check for trusted signature (affects other checks)
    has_trusted_signature = False
    if verify_signatures and has_digital_signature(pdf_data.file_path):
        sig_info = verify_signature_dss(pdf_data.file_path)
        has_trusted_signature = sig_info.get("is_trusted", False)

    # Run all structure checks
    all_flags.extend(check_incremental_updates(pdf_data.file_path, verify_signatures))
    all_flags.extend(check_javascript(pdf_data.file_path))
    all_flags.extend(check_hidden_annotations(pdf_data.file_path))
    all_flags.extend(check_acrobat_text_edit(pdf_data.file_path))
    all_flags.extend(check_editor_marks(pdf_data.file_path))
    all_flags.extend(check_embedded_files(pdf_data.file_path))
    all_flags.extend(check_acroform(pdf_data.file_path))
    all_flags.extend(check_object_streams(pdf_data.file_path, has_trusted_signature))

    # Check creation vs modification time gap
    # A legitimate document is generated once — any modification is suspicious
    all_flags.extend(_metadata_only_modification(
        check_dates(pdf_data.metadata.creation_date, pdf_data.metadata.mod_date),
        pdf_data.file_path,
    ))

    # Check if XMP toolkit reveals a hidden editor
    all_flags.extend(check_xmp_toolkit_mismatch(
        pdf_data.file_path,
        pdf_data.metadata.producer,
        pdf_data.metadata.creator,
    ))

    # Check if the visible creation date was moved earlier than the XMP copy
    all_flags.extend(check_xmp_info_date_mismatch(
        pdf_data.file_path,
        pdf_data.metadata.creation_date,
    ))

    # Calculate score
    score = 100
    for flag in all_flags:
        score -= SEVERITY_POINTS[flag.severity]
    score = max(0, score)

    # High confidence - we can reliably analyze PDF structure
    confidence = 0.95

    return ModuleResult(
        module="structure",
        flags=all_flags,
        score=score,
        confidence=confidence,
    )
