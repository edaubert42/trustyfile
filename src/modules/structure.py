def has_digital_signature(pdf_path: str) -> bool:
    """
    Check if the PDF contains a digital signature field.

    Note: This only checks for PRESENCE of a signature, not validity.
    Use verify_signature_dss() to verify the signature is trusted.

    Args:
        pdf_path: Path to the PDF file

    Returns:
        True if the PDF has a digital signature field
    """
    try:
        doc = fitz.open(pdf_path)
        try:
            # Method 1: Check for signature fields in AcroForm
            for page_num in range(len(doc)):
                page = doc[page_num]
                for widget in page.widgets() or []:
                    if widget.field_type_string == "Signature":
                        return True

            # Method 2: Check for signature objects in the PDF structure
            xref_len = doc.xref_length()
            for xref in range(1, xref_len):
                try:
                    obj_str = doc.xref_object(xref)
                    if obj_str and '/Type /Sig' in obj_str:
                        return True
                    if obj_str and '/SubFilter /adbe.pkcs7' in obj_str:
                        return True
                    if obj_str and '/SubFilter /ETSI' in obj_str:
                        return True
                except Exception:
                    continue

            return False
        finally:
            doc.close()

    except Exception as e:
        logger.error(f"Error checking for digital signature: {e}")
        return False


def count_signature_fields(pdf_path: str) -> int:
    """
    Count SIGNED digital-signature fields in the PDF (no crypto validation).

    Each signing pass appends exactly one incremental update, so the SIGNED
    field count bounds how many updates a legitimately-signed document
    accumulates (e.g. a 3-signer attestation has 3 signed fields, 3 updates).

    Empty/unsigned signature fields are deliberately NOT counted: adding an
    empty field is itself an edit representing zero signing passes — counting
    it would let a fraudster launder a tamper edit by dropping an empty
    AcroForm signature widget into the same incremental save (adversarial-
    review finding, reproduced).

    Returns 0 on any error.
    """
    count = 0
    try:
        doc = fitz.open(pdf_path)
        try:
            for page_num in range(len(doc)):
                for widget in doc[page_num].widgets() or []:
                    if (widget.field_type_string == "Signature"
                            and getattr(widget, "is_signed", False)):
                        count += 1
        finally:
            doc.close()
    except Exception as e:
        logger.error(f"Error counting signature fields: {e}")
        return 0
    return count


def _has_signature_value(pdf_path: str) -> bool:
    """
    True if the PDF contains an actual signature VALUE dictionary — evidence
    a signing pass really happened. An unsigned field only carries /FT /Sig;
    the /Type /Sig (or PKCS7/ETSI SubFilter) value dict exists once signed.
    Used as a fallback when the signed widget is not countable via AcroForm.
    """
    try:
        doc = fitz.open(pdf_path)
        try:
            for xref in range(1, doc.xref_length()):
                try:
                    obj_str = doc.xref_object(xref)
                except Exception:
                    continue
                if obj_str and ('/Type /Sig' in obj_str
                                or '/SubFilter /adbe.pkcs7' in obj_str
                                or '/SubFilter /ETSI' in obj_str):
                    return True
        finally:
            doc.close()
    except Exception as e:
        logger.error(f"Error scanning for signature value: {e}")
    return False


def verify_signature_dss(pdf_path: str) -> dict:
    """
    Report presence of a digital signature WITHOUT uploading the document.

    Phase 0: the previous implementation POSTed the whole PDF to the EU DSS
    demo API, violating the 'document never leaves the machine' constraint.
    Real offline cryptographic validation (ByteRange, chain, post-signing diff)
    arrives in Phase 2 via pyHanko. Until then we only detect presence locally
    and never assert trust.
    """
    present = False
    try:
        present = has_digital_signature(pdf_path)
    except Exception as e:
        logger.error(f"Signature presence check failed: {e}")
    return {
        "has_signature": present,
        "is_valid": False,
        "is_trusted": False,
        "is_fully_valid": False,
        "signer": None,
        "signature_level": "",
        "note": "offline — signature present but not cryptographically verified",
    }


# =============================================================================
# DID THE INCREMENTAL UPDATES CHANGE WHAT THE READER SEES?
# =============================================================================
# Counting revisions says a file was saved again, not that its CONTENT moved.
# Real case: the ZUGFeRD sample invoices from Intarsys carry 4 incremental
# updates — three rewrite only the Info dictionary and the XMP packet, the
# last attaches the Factur-X XML — and every revision renders pixel-identical
# to the final file. They scored REVIEW for "edited 4 times".
#
# So we render the ORIGINAL revision (the bytes up to the first %%EOF) and the
# FINAL file at low resolution and compare pixels. Comparing only these two is
# enough: a change made and later undone falsified nothing visible.
_COMPARE_DPI = 36          # coarse, but any edited glyph or patch moves pixels
_COMPARE_MAX_PAGES = 10    # beyond this, we do not try to prove anything
_REVISION_CACHE: dict[str, dict] = {}
_REVISION_CACHE_MAX = 16
_WHITE = 250               # a pixel channel >= this counts as white paper


def _page_fingerprints(doc) -> list[bytes] | None:
    """Low-resolution render of every page, or None if too many pages."""
    if doc.page_count == 0 or doc.page_count > _COMPARE_MAX_PAGES:
        return None
    prints = []
    for page in doc:
        zoom = safe_zoom(page, _COMPARE_DPI)
        pix = page.get_pixmap(matrix=fitz.Matrix(zoom, zoom), alpha=False)
        # Page size + raw pixels: a resized page must not compare equal.
        prints.append(f"{pix.width}x{pix.height}:".encode() + pix.samples)
    return prints


def _is_blank(fingerprints: list[bytes]) -> bool:
    """True if every page is plain white paper (every channel >= _WHITE)."""
    for fp in fingerprints:
        pixels = fp.split(b":", 1)[1]
        if min(pixels, default=255) < _WHITE:
            return False
    return True


def _revision_comparison(pdf_path: str) -> dict:
    """Compare the original revision with the final file, once per file.

    Returns {"unchanged": bool | None, "original_blank": bool}:
      unchanged       True / False / None, see visible_content_unchanged.
      original_blank  True when the original revision exists and every one
                      of its pages renders as plain white paper.
    Cached by SHA-256: the structure checks ask several times per analysis.
    """
    unknown = {"unchanged": None, "original_blank": False}
    try:
        with open(pdf_path, "rb") as f:
            raw = f.read()
    except OSError as exc:
        logger.warning("revision comparison: cannot read %s: %s", pdf_path, exc)
        return unknown

    key = hashlib.sha256(raw).hexdigest()
    if key in _REVISION_CACHE:
        return _REVISION_CACHE[key]

    result = dict(unknown)
    try:
        positions = find_eof_positions(raw)
        if len(positions) > 1:
            original = fitz.open(stream=raw[:positions[0]], filetype="pdf")
            final = fitz.open(stream=raw, filetype="pdf")
            try:
                before, after = _page_fingerprints(original), _page_fingerprints(final)
                if before is not None and after is not None:
                    result["unchanged"] = before == after
                if before is not None:
                    result["original_blank"] = _is_blank(before)
            finally:
                original.close()
                final.close()
    except Exception as exc:  # malformed revision: say "don't know", never crash
        logger.warning("revision comparison failed for %s: %s", pdf_path, exc)
        result = dict(unknown)

    if len(_REVISION_CACHE) >= _REVISION_CACHE_MAX:
        _REVISION_CACHE.pop(next(iter(_REVISION_CACHE)))   # drop the oldest entry
    _REVISION_CACHE[key] = result
    return result


def visible_content_unchanged(pdf_path: str) -> bool | None:
    """Do all pages of the final file render exactly like the original revision?

    Returns:
        True  — the file has incremental updates and none changed a pixel of
                any page (only metadata, attachments, invisible structure).
        False — at least one page renders differently: the content was edited.
        None  — cannot tell: no incremental update, more than
                _COMPARE_MAX_PAGES pages, or a revision that will not open.
                Callers must then keep their cautious behaviour.

    Example:
        Intarsys ZUGFeRD_1p0_BASIC_Einfach.pdf (5 revisions, metadata-only)
        -> True
        A total retyped in an incremental save -> False
    """
    return _revision_comparison(pdf_path)["unchanged"]


def original_revision_blank(pdf_path: str) -> bool:
    """Was the original revision a blank page that later saves wrote onto?

    Some pipelines start from an empty page and write the whole document in
    an incremental update. Nothing pre-existing was altered: the "edit" is
    the document's creation. Real case: symtrax ZUGFeRD 2.1 sample — macOS
    Preview blank A4 page (a white image), then iTextSharp writes 2 pages of
    invoice over it.

    Example:
        symtrax zugferd_2p1_EN16931_Reisekostenabrechnung.pdf -> True
        A total retyped in an incremental save -> False (original had text)
    """
    return _revision_comparison(pdf_path)["original_blank"]


def original_revision_unmodified(pdf_path: str) -> bool:
    """True if the revision before the first incremental update was never modified.

    "Never modified" = its Info ModDate is absent, or within 2 seconds of its
    CreationDate (the same tolerance as check_dates). Then every later
    modification lives in the incremental updates, which
    visible_content_unchanged can inspect.

    Example:
        Intarsys ZUGFeRD sample: original revision has no ModDate -> True
    """
    from src.extractors.pdf_extractor import parse_pdf_date
    try:
        with open(pdf_path, "rb") as f:
            raw = f.read()
        positions = find_eof_positions(raw)
        if len(positions) <= 1:
            return False
        original = fitz.open(stream=raw[:positions[0]], filetype="pdf")
        try:
            meta = original.metadata or {}
        finally:
            original.close()
    except Exception as exc:
        logger.warning("original_revision_unmodified failed for %s: %s", pdf_path, exc)
        return False
    created = parse_pdf_date(meta.get("creationDate"))
    modified = parse_pdf_date(meta.get("modDate"))
    if modified is None:
        return True
    return created is not None and abs((modified - created).total_seconds()) <= 2


def count_incremental_updates(pdf_path: str) -> int:
    """
    Count the number of incremental updates (revisions) in a PDF.

    Each time a PDF is edited and saved, a new "%%EOF" marker is added.
    A clean PDF has exactly 1 EOF. Multiple EOFs = multiple edits.

    Args:
        pdf_path: Path to the PDF file

    Returns:
        Number of EOF markers found (1 = clean, >1 = edited)
    """
    try:
        with open(pdf_path, 'rb') as f:
            content = f.read()

        # One version per real %%EOF (find_eof_positions skips the extra
        # marker of a linearized file, which is not an edit).
        return len(find_eof_positions(content))
    except Exception as e:
        logger.error(f"Error counting incremental updates: {e}")
        return 1  # Assume clean if we can't read


def check_incremental_updates(pdf_path: str, verify_signatures: bool = True) -> list[Flag]:
    """
    Check if the PDF has been edited (has incremental updates).

    If a TRUSTED digital signature is present (verified via EU DSS API),
    1 incremental update is expected and legitimate.
    An untrusted or invalid signature does NOT excuse incremental updates.

    Args:
        pdf_path: Path to the PDF file
        verify_signatures: Whether to verify signatures via DSS API

    Returns:
        List of flags if suspicious updates detected
    """
    flags = []

    eof_count = count_incremental_updates(pdf_path)

    if eof_count <= 1:
        return flags  # No incremental updates, clean PDF

    edits = eof_count - 1

    # Check for digital signature
    has_signature = has_digital_signature(pdf_path)
    signature_info = {}

    if has_signature and verify_signatures:
        # Local, presence-only verification (document never leaves the machine)
        signature_info = verify_signature_dss(pdf_path)

        # Add flag about signature status
        signer = signature_info.get("signer", "Unknown")
        level = signature_info.get("signature_level", "")

        if signature_info.get("is_trusted"):
            # Signature uses Qualified Certificate from EU Trusted List
            if signature_info.get("is_fully_valid"):
                # Fully validated
                flags.append(Flag(
                    severity="low",  # Informational - excellent signature
                    code="STRUCT_SIGNATURE_TRUSTED",
                    message=f"Document has EU trusted signature: {signer} ({level})",
                    details=signature_info
                ))
            else:
                # QC but not fully valid (e.g., cert expired but was valid at signing time)
                flags.append(Flag(
                    severity="low",  # Still trustworthy - QC from EU list
                    code="STRUCT_SIGNATURE_TRUSTED_EXPIRED",
                    message=f"Document has EU trusted signature (certificate may be expired): {signer}",
                    details=signature_info
                ))
        elif signature_info.get("is_valid"):
            # Valid signature but not from EU trusted list
            flags.append(Flag(
                severity="medium",
                code="STRUCT_SIGNATURE_NOT_TRUSTED",
                message=f"Document has signature but NOT from EU trusted list: {signer}",
                details=signature_info
            ))
        elif signature_info.get("unverifiable"):
            # Signature present but couldn't be verified
            flags.append(Flag(
                severity="medium",
                code="STRUCT_SIGNATURE_UNVERIFIABLE",
                message="Document has signature but format not recognized by EU DSS",
                details=signature_info
            ))
        elif signature_info.get("is_invalid"):
            # Cryptographically verified and REJECTED (future pyHanko path).
            # The offline presence-only verifier never sets this.
            flags.append(Flag(
                severity="high",
                code="STRUCT_SIGNATURE_INVALID",
                message="Document has INVALID digital signature",
                details=signature_info
            ))
        elif signature_info.get("has_signature"):
            # Signature present but NOT verified (offline verifier never
            # asserts validity). Calling this "INVALID" was a verified audit
            # FP — every legitimately signed document was flagged high.
            flags.append(Flag(
                severity="low",  # informational, like the trusted branches
                code="STRUCT_SIGNATURE_UNVERIFIED",
                message="Document has a digital signature (present, not cryptographically verified locally)",
                details=signature_info
            ))

    # A REAL signature explains incremental updates: each signing pass appends
    # exactly one. Excuse up to one update per SIGNED field — a 3-signer
    # attestation with 3 updates is routine, not "edited 3 times". Edits
    # BEYOND the signed count remain fully suspicious, and an empty/unsigned
    # signature field excuses NOTHING (adding it is itself an edit — a
    # fraudster could otherwise launder a tamper edit with an empty widget).
    # (Previously only `signature_trusted` excused updates, but the offline
    # verifier can never assert trust, so signed docs were always penalized.)
    excused = 0
    if has_signature:
        signed_count = count_signature_fields(pdf_path)
        if signed_count > 0:
            excused = signed_count
        elif _has_signature_value(pdf_path):
            # A signature value exists but isn't countable via AcroForm
            # widgets (e.g. object-level signature) — excuse one signing pass.
            excused = 1
    effective_edits = edits - excused

    if effective_edits <= 0:
        return flags

    # Severity based on number of edits
    if effective_edits >= 3:
        severity = "critical"
        message = f"PDF has been edited {effective_edits} times (very suspicious)"
    elif effective_edits == 2:
        severity = "high"
        message = f"PDF has been edited {effective_edits} times"
    else:
        severity = "medium"
        message = f"PDF has {effective_edits} incremental update(s)"

    # Saved again, but nothing the reader sees changed: every page of the
    # final file renders exactly like the original revision (metadata, XMP,
    # attached Factur-X XML...). Still reported, at "low" weight.
    visible_changed = None
    unchanged = visible_content_unchanged(pdf_path)
    blank_original = original_revision_blank(pdf_path)
    if unchanged is True:
        severity = "low"
        visible_changed = False
        message = (f"PDF was saved {effective_edits} more time(s), but every page "
                   f"renders exactly like the original: only metadata or "
                   f"attachments changed")
    elif blank_original:
        # The first version was blank paper: the later save(s) WROTE the
        # document, they did not alter existing content.
        severity = "low"
        visible_changed = True
        message = (f"PDF was saved {effective_edits} more time(s); its first "
                   f"version was a blank page, so the content was written then "
                   f"(the document's creation, not an edit)")
    elif unchanged is False:
        visible_changed = True

    # Add context when edits exceed what the signature(s) can explain
    if has_signature:
        message += f" (beyond the {excused} explained by signing passes)"

    flags.append(Flag(
        severity=severity,
        code="STRUCT_INCREMENTAL_UPDATES",
        message=message,
        details={
            "eof_count": eof_count,
            "edit_count": edits,
            "has_signature": has_signature,
            "excused_by_signatures": excused,
            "effective_edits": effective_edits,
            "visible_content_changed": visible_changed,
            "original_blank": blank_original,
            "explanation": "Each edit adds a new version to the PDF. "
                          "Each signature field excuses one update (a signing "
                          "pass appends exactly one version)."
        }
    ))

    # Check if ModDate was NOT updated despite incremental updates.
    # A legitimate editor (Adobe, LibreOffice) always updates ModDate.
    # If the file was modified but ModDate == CreationDate, the editor
    # deliberately hid the modification — very suspicious.
    try:
        doc = fitz.open(pdf_path)
        try:
            meta = doc.metadata
        finally:
            doc.close()
        raw_creation = meta.get("creationDate", "")
        raw_mod = meta.get("modDate", "")
        if raw_creation and raw_mod and raw_creation == raw_mod:
            # "Hid its traces" assumes visible content was altered. When the
            # pages render like the original, or the original was blank paper
            # the later save wrote onto, nothing pre-existing was modified:
            # an unchanged ModDate hides nothing. Reported at "low".
            nothing_altered = unchanged is True or blank_original
            flags.append(Flag(
                severity="low" if nothing_altered else "high",
                code="STRUCT_HIDDEN_MODIFICATION",
                message=("PDF was saved again without updating its modification "
                         "date, but no existing content was altered"
                         if nothing_altered else
                         "PDF was modified but modification date was not updated "
                         "(editor hid its traces)"),
                details={
                    "nothing_altered": nothing_altered,
                    "creation_date": raw_creation,
                    "mod_date": raw_mod,
                    "incremental_updates": effective_edits,
                    "explanation": "The PDF has incremental updates (proof of editing) "
                                  "but the modification date is identical to the creation date. "
                                  "A legitimate editor always updates the modification date.",
                }
            ))
    except Exception:
        pass  # Don't crash if metadata can't be read

    return flags


def check_javascript(pdf_path: str) -> list[Flag]:
    """
    Check if the PDF contains JavaScript.

    JavaScript in a PDF is very suspicious for invoices/certificates.
    It could be used for:
    - Malware delivery
    - Dynamic content modification
    - Phishing attacks

    Args:
        pdf_path: Path to the PDF file

    Returns:
        List of flags if JavaScript detected
    """
    flags = []

    try:
        doc = fitz.open(pdf_path)
        try:
            # Check for JavaScript in the document
            # PyMuPDF can extract JS from various locations

            # Method 1: Check document-level JavaScript
            js_found = False
            js_locations = []

            # Check PDF catalog for JavaScript
            try:
                # Get the PDF trailer/catalog
                xref_len = doc.xref_length()

                for xref in range(1, xref_len):
                    try:
                        obj_str = doc.xref_object(xref)
                        if obj_str:
                            # Look for JavaScript indicators
                            if '/JavaScript' in obj_str or '/JS' in obj_str:
                                js_found = True
                                js_locations.append(f"xref {xref}")
                    except Exception:
                        continue
            except Exception as e:
                logger.debug(f"Error checking xref for JS: {e}")

            # Method 2: Check for JavaScript in annotations
            for page_num in range(len(doc)):
                page = doc[page_num]

                # Check annotations
                for annot in page.annots() or []:
                    annot_info = annot.info
                    if annot_info:
                        # Check for JavaScript actions
                        if 'javascript' in str(annot_info).lower():
                            js_found = True
                            js_locations.append(f"annotation on page {page_num + 1}")
        finally:
            doc.close()

        if js_found:
            # HIGH, not critical (2026-07 judge panel): a raw '/JS' substring
            # scan — Acrobat/LiveCycle fillable invoices and government/tax
            # forms routinely embed field-calculation JavaScript legitimately.
            flags.append(Flag(
                severity="high",
                code="STRUCT_JAVASCRIPT_DETECTED",
                message="PDF contains JavaScript code (suspicious for static documents)",
                details={
                    "locations": js_locations,
                    "warning": "JavaScript in PDFs can be used for malware or phishing, "
                              "though fillable forms embed calculation scripts legitimately."
                }
            ))

    except Exception as e:
        logger.error(f"Error checking for JavaScript: {e}")

    return flags


# Annotations a READER adds on top of a finished page: pen strokes, text
# boxes, shapes, highlights, stamps, sticky notes. page.annots() already
# leaves out links and form widgets, which issuers do produce. Measured
# 2026-11-12: none in the 171 non-suspicious local samples; the four test
# invoices edited online with ink or highlight carry them.
MARKUP_ANNOTATION_TYPES: frozenset[str] = frozenset({
    "Ink", "FreeText", "Square", "Circle", "Line", "Polygon", "PolyLine",
    "Highlight", "Underline", "StrikeOut", "Squiggly", "Stamp", "Caret",
    "Text", "Redact",
})


def check_hidden_annotations(pdf_path: str) -> list[Flag]:
    """
    Check for hidden or suspicious annotations in the PDF.

    Annotations can contain:
    - Hidden comments (review history)
    - Invisible links
    - Form fields
    - Redactions (covered content)

    Args:
        pdf_path: Path to the PDF file

    Returns:
        List of flags if suspicious annotations found
    """
    flags = []

    try:
        doc = fitz.open(pdf_path)
        try:
            hidden_annots = []
            suspicious_annots = []
            markup_annots = []

            for page_num in range(len(doc)):
                page = doc[page_num]

                for annot in page.annots() or []:
                    annot_type = annot.type[1]  # Get annotation type name

                    # Check for hidden annotations (opacity = 0 or invisible flag)
                    if annot.opacity == 0:
                        hidden_annots.append({
                            "page": page_num + 1,
                            "type": annot_type,
                            "reason": "opacity is 0 (invisible)"
                        })

                    # Check for suspicious annotation types
                    suspicious_types = ['FileAttachment', 'Sound', 'Movie', 'Screen', 'RichMedia']
                    if annot_type in suspicious_types:
                        suspicious_annots.append({
                            "page": page_num + 1,
                            "type": annot_type,
                            "reason": f"suspicious type: {annot_type}"
                        })

                    if annot_type in MARKUP_ANNOTATION_TYPES:
                        markup_annots.append({"page": page_num + 1, "type": annot_type})
        finally:
            doc.close()

        if markup_annots:
            types = sorted({a["type"] for a in markup_annots})
            flags.append(Flag(
                severity="high",
                code="STRUCT_MARKUP_ANNOTATIONS",
                message=(f"Someone drew or wrote on the document after it was "
                         f"issued ({', '.join(types)})"),
                details={
                    "annotations": markup_annots[:10],
                    "explanation": "Drawings, highlights and text boxes are added "
                                   "by a reader, never by the issuer's software. "
                                   "They can also hide or overwrite printed values.",
                }
            ))

        if hidden_annots:
            flags.append(Flag(
                severity="high",
                code="STRUCT_HIDDEN_ANNOTATIONS",
                message=f"PDF contains {len(hidden_annots)} hidden annotation(s)",
                details={
                    "annotations": hidden_annots,
                    "explanation": "Hidden annotations may contain concealed information."
                }
            ))

        if suspicious_annots:
            flags.append(Flag(
                severity="high",
                code="STRUCT_SUSPICIOUS_ANNOTATIONS",
                message=f"PDF contains suspicious annotation types",
                details={
                    "annotations": suspicious_annots,
                    "explanation": "These annotation types are unusual for invoices."
                }
            ))

    except Exception as e:
        logger.error(f"Error checking annotations: {e}")

    return flags


def check_acrobat_text_edit(pdf_path: str) -> list[Flag]:
    """Flag text that was changed with Acrobat's "Edit text" tool.

    Acrobat leaves a /TouchUp_TextEdit marker in the page next to the text it
    rewrote (see src/modules/acrobat_edit.py). The marker is in the page
    itself, so it is still there after the file's dates, XMP and revisions
    have been wiped by a rewrite.

    The flag lists the visible lines sitting next to a marker, each with its
    page and box, in the "instances" shape the preview draws.

    Args:
        pdf_path: Path to the PDF file.

    Returns:
        One high flag when at least one marker is found, else an empty list.

    Example:
        Invoice whose recipient block was retyped in Acrobat ->
        [Flag(high, STRUCT_ACROBAT_TEXT_EDIT, details={"marker_count": 2,
          "instances": [{"page": 0, "bbox": (301, 231, 531, 243),
                         "text": "Destinataire : EDOUARD AUBERT"}, ...]})]
    """
    edits = find_acrobat_text_edits(pdf_path)
    if edits.marker_count == 0:
        return []

    return [Flag(
        severity="high",
        code="STRUCT_ACROBAT_TEXT_EDIT",
        message=(f"Text was edited with Adobe Acrobat's text tool "
                 f"({edits.marker_count} edit marker(s) in the page content)"),
        details={
            "marker_count": edits.marker_count,
            # page is 0-based here, like every other "instances" entry
            "instances": [{"page": line.page, "bbox": line.bbox, "text": line.text}
                          for line in edits.lines],
            "explanation": "Acrobat marks the text blocks its edit tool rewrote. "
                           "The lines listed sit next to a marker: the change "
                           "is in one of them. An issuer's software does not "
                           "leave this marker, a manual edit does.",
        },
    )]


def check_editor_marks(pdf_path: str) -> list[Flag]:
    """Flag the marks a PDF editor left in the page content.

    Two flags, both read from the page itself, so both still there after the
    file's dates, XMP and revisions have been wiped by a rewrite (see
    src/modules/editor_marks.py for the marks and the corpus measurements):

      STRUCT_EDITOR_MARKER        an editor's own named marker (Adobe Fill &
                                  Sign, Wondershare PDFelement, Iceni Infix)
      STRUCT_EMPTY_TEXT_OPERATOR  a text operator that draws nothing: what is
                                  left when an editor deletes text

    Args:
        pdf_path: Path to the PDF file.

    Returns:
        Zero, one or two high flags.

    Example:
        Invoice with a line typed over it in Adobe Fill & Sign ->
        [Flag(high, STRUCT_EDITOR_MARKER, details={"editors": {"Adobe Fill &
          Sign": 1}, "instances": [{"page": 0, "bbox": (341, 178, 392, 191),
          "text": "Remise 30 %"}]})]
    """
    marks = find_editor_marks(pdf_path)
    flags: list[Flag] = []

    if marks.editors:
        names = ", ".join(sorted(marks.editors))
        flags.append(Flag(
            severity="high",
            code="STRUCT_EDITOR_MARKER",
            message=(f"Content was added or edited with {names} "
                     f"({sum(marks.editors.values())} marker(s) in the page content)"),
            details={
                "editors": dict(marks.editors),
                # page is 0-based here, like every other "instances" entry
                "instances": [{"page": line.page, "bbox": line.bbox, "text": line.text}
                              for line in marks.lines],
                "explanation": "This editor marks the content it adds or takes "
                               "over. The lines listed are drawn inside its "
                               "marks. An issuer's software does not leave "
                               "them, a manual edit does.",
            },
        ))

    if marks.empty_text_operators:
        flags.append(Flag(
            severity="high",
            code="STRUCT_EMPTY_TEXT_OPERATOR",
            message=(f"{marks.empty_text_operators} text operator(s) in the page "
                     f"content draw nothing: text was deleted by an editor"),
            details={
                "count": marks.empty_text_operators,
                "explanation": "A page draws text with an operator that holds "
                               "the characters. Here the operator is still "
                               "there and its characters are gone. Software "
                               "that generates a document does not write that; "
                               "an editor removing text does.",
            },
        ))
    return flags


def check_embedded_files(pdf_path: str) -> list[Flag]:
    """
    Check for embedded files in the PDF.

    Embedded files can be used to hide:
    - Malware
    - Additional documents
    - Executable code

    Args:
        pdf_path: Path to the PDF file

    Returns:
        List of flags if embedded files found
    """
    flags = []

    try:
        doc = fitz.open(pdf_path)
        try:
            # Get embedded files
            embedded_count = doc.embfile_count()

            embedded_files = []
            for i in range(embedded_count):
                info = doc.embfile_info(i)
                embedded_files.append({
                    "name": info.get("name", "unknown"),
                    "size": info.get("size", 0),
                })
        finally:
            doc.close()

        if embedded_count > 0:
            # Classify each embedded file. IMPORTANT (security): the decision is
            # PER FILE, never per document — a recognised e-invoice XML excuses
            # only ITSELF, never other payloads riding along beside it. The threat
            # is hidden ACTIVE or OPAQUE content, so:
            #   - dangerous : active-content extensions -> always critical
            #   - einvoice  : the required Factur-X/ZUGFeRD/XRechnung XML -> never flagged
            #   - benign    : transparent doc/image companions (delivery note, logo) —
            #                 expected in an e-invoice, not flagged there
            #   - opaque    : archives / blobs / unknown types -> always surfaced
            # NOTE: extension-based typing can be spoofed (rename a blob to .pdf).
            # That residual is accepted: TrustyFile never opens/executes attachments,
            # and every executable or opaque payload is still surfaced or blocked.
            # Pure executables: ~zero legit rate inside an invoice → critical.
            executable_extensions = ['.exe', '.js', '.jse', '.vbs', '.bat', '.cmd',
                                     '.ps1', '.dll', '.jar', '.scr', '.com', '.msi',
                                     '.hta', '.wsf', '.lnk']
            # Macro-enabled Office documents are common malware carriers, but
            # accounts-payable workflows DO attach legit macro spreadsheets
            # (reconciliation/order templates) → high, not critical
            # (2026-07 judge panel).
            macro_office_extensions = ['.docm', '.xlsm', '.xlsb', '.xlam', '.xltm',
                                       '.dotm', '.pptm', '.potm']
            dangerous_extensions = executable_extensions + macro_office_extensions
            benign_companion_extensions = ['.pdf', '.xml', '.txt', '.csv', '.png',
                                           '.jpg', '.jpeg', '.tif', '.tiff', '.gif']

            def _ext_in(name: str, exts: list) -> bool:
                return any(name.lower().endswith(ext) for ext in exts)

            dangerous_files = [f for f in embedded_files if _ext_in(f["name"], dangerous_extensions)]
            einvoice_files = [f for f in embedded_files if is_einvoice_attachment(f["name"])]
            companion_files = [f for f in embedded_files
                               if not _ext_in(f["name"], dangerous_extensions)
                               and not is_einvoice_attachment(f["name"])]

            if dangerous_files:
                # Executable/active content is dangerous regardless of any
                # factur-x.xml sitting next to it — the allowlist never excuses it.
                only_macro = all(_ext_in(f["name"], macro_office_extensions)
                                 for f in dangerous_files)
                flags.append(Flag(
                    severity="high" if only_macro else "critical",
                    code="STRUCT_EMBEDDED_FILES",
                    message=("PDF contains embedded macro-enabled Office file(s) (active content)"
                             if only_macro else
                             "PDF contains embedded executable files (malware risk!)"),
                    details={"file_count": len(dangerous_files), "files": dangerous_files,
                             "warning": "Embedded active content is dangerous."},
                ))
            elif einvoice_files:
                # Recognised structured e-invoice. Transparent document/image
                # companions are expected; only OPAQUE payloads are surfaced (low),
                # so a hidden blob can never ride along unflagged.
                opaque = [f for f in companion_files
                          if not _ext_in(f["name"], benign_companion_extensions)]
                if opaque:
                    flags.append(Flag(
                        severity="low",
                        code="STRUCT_EMBEDDED_FILES",
                        message=f"e-invoice carries {len(opaque)} opaque attachment(s)",
                        details={"file_count": len(opaque), "files": opaque,
                                 "warning": "Opaque (non-document) attachment in an e-invoice — review."},
                    ))
                else:
                    logger.info("e-invoice with recognised XML + document companions — not flagged")
            elif companion_files:
                # Non-e-invoice PDF with unexplained embedded files — original suspicion.
                flags.append(Flag(
                    severity="high",
                    code="STRUCT_EMBEDDED_FILES",
                    message=f"PDF contains {len(companion_files)} embedded file(s)",
                    details={"file_count": len(companion_files), "files": companion_files,
                             "warning": "Embedded files in invoices are suspicious."},
                ))

    except Exception as e:
        logger.error(f"Error checking embedded files: {e}")

    return flags


def check_acroform(pdf_path: str) -> list[Flag]:
    """
    Check for AcroForm (interactive forms) in the PDF.

    While forms are legitimate in some contexts, they're suspicious
    in invoices because they can be used to:
    - Collect data (phishing)
    - Execute JavaScript
    - Modify displayed content

    Note: Signature fields are excluded - they are legitimate for signed documents.

    Args:
        pdf_path: Path to the PDF file

    Returns:
        List of flags if forms detected
    """
    flags = []

    try:
        doc = fitz.open(pdf_path)
        try:
            # Check for form fields
            form_fields = []
            signature_fields = []

            for page_num in range(len(doc)):
                page = doc[page_num]

                # Get widgets (form fields)
                widgets = page.widgets()
                if widgets:
                    for widget in widgets:
                        field_info = {
                            "page": page_num + 1,
                            "type": widget.field_type_string,
                            "name": widget.field_name or "unnamed",
                        }

                        # Separate signature fields from other form fields
                        if widget.field_type_string == "Signature":
                            signature_fields.append(field_info)
                        else:
                            form_fields.append(field_info)
        finally:
            doc.close()

        # Only flag non-signature form fields
        # Signature fields are legitimate for digitally signed documents
        if form_fields:
            flags.append(Flag(
                severity="medium",
                code="STRUCT_ACROFORM_DETECTED",
                message=f"PDF contains {len(form_fields)} interactive form field(s)",
                details={
                    "fields": form_fields[:10],  # Limit to first 10
                    "total_count": len(form_fields),
                    "note": "Interactive forms are unusual in invoices."
                }
            ))

    except Exception as e:
        logger.error(f"Error checking AcroForm: {e}")

    return flags


def find_free_xrefs(doc: "fitz.Document") -> list[int]:
    """
    List the xref numbers of deleted or nulled-out objects, format-agnostically.

    PyMuPDF returns the literal body ``"null"`` for a free (deleted) xref
    slot, and it resolves the lookup through MuPDF's own cross-reference
    abstraction, so this works identically for:

    - classic ASCII xref tables (``nnnnnnnnnn ggggg f`` entries), and
    - PDF 1.5+ cross-reference STREAMS, where entries are packed binary
      inside a Flate-compressed stream object and no literal ``f`` exists
      anywhere in the file.

    KNOWN AMBIGUITY, accepted deliberately: an in-use object whose body is
    the literal PDF ``null`` keyword is indistinguishable through this API
    from a genuinely free slot (verified empirically on PyMuPDF 1.28 — no
    available API separates them). We COUNT those too, on purpose: writing
    ``null`` over an object's body is how some editors and redaction tools
    soft-delete content without renumbering, which is exactly the editing
    trace this check exists to surface. The flag message says "deleted
    objects (ghost data)" and both patterns qualify.

    The previous implementation grepped the raw bytes for the classic ASCII
    form — completely blind on xref-stream files, and it also counted the
    spec-mandated free-list head entry for object 0 (present in every
    classic table, one per revision) as if it were a real deletion.

    Args:
        doc: An open fitz Document.

    Returns:
        Sorted list of xref numbers whose slot is free or whose object was
        nulled out. Object 0 (the permanent free-list head, invalid to
        query) is excluded.
    """
    free: list[int] = []
    for xref in range(1, doc.xref_length()):
        try:
            body = doc.xref_object(xref)
        except Exception:
            # A slot MuPDF cannot resolve at all; not evidence of anything.
            continue
        # NOTE: xref_get_key(x, "Type") == ("null", "null") is NOT a valid
        # test — it also matches live objects that simply have no /Type key.
        # The whole body must be "null" (free slot or nulled-out object).
        if body is not None and body.strip() == "null":
            free.append(xref)
    return free


def check_object_streams(pdf_path: str, has_trusted_signature: bool = False) -> list[Flag]:
    """
    Check for deleted-but-still-present objects (ghost data).

    Each free xref slot is an object that existed and was deleted; on a
    document that claims to come out of a single-pass generator, many such
    slots mean the file has an editing history.

    Args:
        pdf_path: Path to the PDF file
        has_trusted_signature: If True, allows more deleted objects (signing creates them)

    Returns:
        List of flags if suspicious patterns found
    """
    flags = []

    try:
        doc = fitz.open(pdf_path)
    except Exception as e:
        logger.error(f"Error checking object streams: {e}")
        return flags

    try:
        free_xrefs = find_free_xrefs(doc)
    except Exception as e:
        logger.error(f"Error checking object streams: {e}")
        return flags
    finally:
        doc.close()

    free_objects = len(free_xrefs)

    # Thresholds are lower than the historical 10/15: the old byte-regex
    # counted one guaranteed false entry per revision (object 0's head
    # entry), so its thresholds carried built-in noise. find_free_xrefs
    # counts only real deletions/nullings. Calibration snapshot 2026-08-13:
    # max 2 across the 94 local samples/ PDFs (the corpus band gates in
    # tests/ would catch a regression end-to-end); still provisional
    # beyond that corpus.
    if has_trusted_signature:
        threshold = 10  # Signing workflows legitimately free objects
        explanation = ("Deleted objects may contain previous versions of content. "
                       "For signed documents, some deleted objects are normal.")
    else:
        threshold = 5  # Some PDF generators create/delete temp objects normally
        explanation = ("Deleted objects may contain previous versions of content. "
                       "An unsigned document should have minimal deleted objects.")

    if free_objects > threshold:
        flags.append(Flag(
            severity="medium",
            code="STRUCT_DELETED_OBJECTS",
            message=f"PDF contains {free_objects} deleted objects (ghost data)",
            details={
                "free_objects": free_objects,
                # First few xref numbers, for the reviewer; the full list
                # can be long and adds nothing.
                "free_xrefs": free_xrefs[:20],
                "threshold": threshold,
                "has_trusted_signature": has_trusted_signature,
                "explanation": explanation,
            }
        ))

    return flags


