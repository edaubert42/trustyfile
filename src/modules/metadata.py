# Virtual printers: the PDF is a re-print of what was on screen, not the file
# the issuer's software wrote. Small issuers use them legitimately (FACA prints
# its invoices through PDFCreator), but so does anyone who edits an invoice on
# screen and prints it again: every trace of the edit is gone. So the origin
# cannot be verified, and an issued document never reaches GENUINE
# (scoring.UNVERIFIED_ORIGIN_CODES). Chrome's "Skia/PDF" and macOS "Quartz" are
# not listed: they are also how web portals and Mac apps export directly.
VIRTUAL_PRINTERS = [
    "print to pdf",   # Microsoft: Print To PDF
    "pdfcreator",
    "cutepdf",
    "dopdf",
    "bullzip",
    "novapdf",
    "primopdf",
    "cups-pdf",
]


def check_virtual_printer(producer: str | None, creator: str | None) -> list[Flag]:
    """Flag a PDF written by a virtual printer.

    Example:
        >>> check_virtual_printer("Microsoft: Print To PDF", None)[0].code
        'META_VIRTUAL_PRINTER'
    """
    combined = f"{producer or ''} {creator or ''}".lower()
    for printer in VIRTUAL_PRINTERS:
        if printer in combined:
            return [Flag(
                severity="low",
                code="META_VIRTUAL_PRINTER",
                message=f"Document was printed to PDF through a virtual printer: {printer}",
                details={"producer": producer, "creator": creator,
                         "detected_tool": printer},
            )]
    return []


def analyze_metadata(pdf_data: PDFData) -> ModuleResult:
    """
    Main function: Analyze PDF metadata for signs of manipulation.

    This is the entry point called by the main analyzer.
    It runs all checks and combines results into a ModuleResult.

    Args:
        pdf_data: Extracted PDF data from pdf_extractor

    Returns:
        ModuleResult with score, flags, and confidence

    Example:
        >>> from src.extractors.pdf_extractor import extract_pdf_data
        >>> pdf_data = extract_pdf_data("invoice.pdf")
        >>> result = analyze_metadata(pdf_data)
        >>> print(f"Score: {result.score}, Flags: {len(result.flags)}")
    """
    all_flags = []

    # Run all checks
    all_flags.extend(check_producer(
        pdf_data.metadata.producer,
        pdf_data.metadata.creator,
    ))

    all_flags.extend(check_virtual_printer(
        pdf_data.metadata.producer,
        pdf_data.metadata.creator,
    ))

    # Date checks (creation vs modification gap) are now in structure module
    # because they relate to document modifications, not metadata quality

    all_flags.extend(check_missing_metadata(pdf_data.raw_metadata))
    all_flags.extend(check_malformed_dates(pdf_data.raw_metadata))

    # PyMuPDF had to REPAIR the file structure to open it. Sloppy producers
    # emit malformed PDFs, but hand-edited bytes are the classic cause —
    # a medium note (2026-07 audit: the extractor computed this signal and
    # nothing consumed it).
    if getattr(pdf_data, "is_repaired", False):
        all_flags.append(Flag(
            severity="medium",
            code="META_DOCUMENT_REPAIRED",
            message="PDF structure was broken and had to be repaired to open",
            details={"explanation": "The file's internal structure did not parse "
                                    "cleanly — either a sloppy generator or "
                                    "hand-edited file bytes."},
        ))

    # Calculate score: start at 100, subtract points for each flag
    score = 100
    for flag in all_flags:
        score -= SEVERITY_POINTS[flag.severity]

    # Score can't go below 0
    score = max(0, score)

    # Calculate confidence
    # High confidence if we have metadata to analyze
    # Low confidence if metadata is missing (we can't say much)
    has_producer = bool(pdf_data.metadata.producer or pdf_data.metadata.creator)
    has_dates = bool(pdf_data.metadata.creation_date)

    if has_producer and has_dates:
        confidence = 1.0  # We have everything we need
    elif has_producer or has_dates:
        confidence = 0.7  # Partial information
    else:
        confidence = 0.3  # Very little to analyze

    return ModuleResult(
        module="metadata",
        flags=all_flags,
        score=score,
        confidence=confidence,
    )
