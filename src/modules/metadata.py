def check_producer(
    producer: str | None,
    creator: str | None,
) -> list[Flag]:
    """
    Check if the producer/creator software is suspicious.

    Args:
        producer: PDF Producer field (software that created the final PDF)
        creator: PDF Creator field (original application)

    Returns:
        List of Flag objects for any suspicious findings

    Example:
        >>> check_producer("iLovePDF", None)
        [Flag(severity="high", code="META_ONLINE_CONVERTER", ...)]

    Note:
        The Author field is intentionally NEVER scanned by any fingerprint
        list here (audit item 20 tried it, then reverted it — 2026-07
        review). Producer/Creator are software-reported fields, so a tool
        name showing up there is meaningful signal. Author is different:
        Word/LibreOffice routinely stamp the OS user's real person or
        company name into it, and several fingerprint tokens collide with
        ordinary names — "canva"/"acorn" (image-editor list) matched
        "Canvas Prints Ltd" / "Acorn Accounting", "nitro" (converter list)
        matched "Nitro Inc" — a confirmed high-severity false-positive
        source. Same precedent as AI_LLM_PRODUCERS already never scanning
        Author (bare given-name tokens like "claude"/"bard" collide with
        human first names).
    """
    flags = []

    # Combine producer and creator for checking (either could contain the
    # tool name). Convert to lowercase for case-insensitive matching. Author
    # is deliberately EXCLUDED — see the "Note" in the docstring above.
    producer_lower = (producer or "").lower()
    creator_lower = (creator or "").lower()
    combined = f"{producer_lower} {creator_lower}"

    # Check for image editors — a PDF produced by an image editor is very suspicious
    # for official documents. It means someone opened/modified an image then exported as PDF.
    IMAGE_EDITORS = [
        "paint.net", "paint net", "photoshop", "gimp", "krita", "pixlr",
        "affinity photo", "corel photo", "photopea", "canva",
        "paint shop pro", "acorn", "pixelmator",
    ]
    for editor in IMAGE_EDITORS:
        if editor in combined:
            flags.append(Flag(
                severity="high",
                code="META_IMAGE_EDITOR",
                message=f"Document was produced by image editor: {editor}",
                details={
                    "producer": producer,
                    "creator": creator,
                    "detected_tool": editor,
                    "explanation": "Official documents are never created with image editors. "
                                   "This strongly suggests the document was visually modified.",
                }
            ))
            return flags  # No need to check further

    # Check for image-to-PDF conversion (scans, mobile apps, conversion tools)
    # Less suspicious — scans are legitimate, but worth noting.
    IMAGE_CONVERSION_KEYWORDS = ["image conversion", "image to pdf", "img2pdf", "photo to pdf"]
    for keyword in IMAGE_CONVERSION_KEYWORDS:
        if keyword in combined:
            flags.append(Flag(
                severity="low",
                code="META_IMAGE_CONVERSION",
                message="Document was created by converting an image to PDF (possible scan)",
                details={
                    "producer": producer,
                    "creator": creator,
                }
            ))
            break

    # Check for AI/LLM tools first (most suspicious for invoices).
    # MEDIUM, not critical (2026-07 judge panel): a bare substring match on a
    # self-reported, spoofable metadata field, and several keywords are brand
    # names with legit collision paths (Microsoft 365 "Copilot" drafting,
    # "Gemini"-branded utilities, a user literally named Claude).
    for ai_tool in AI_LLM_PRODUCERS:
        if ai_tool in combined:
            flags.append(Flag(
                severity="medium",
                code="META_AI_GENERATED",
                message=f"Document appears to be generated by AI tool: {ai_tool}",
                details={
                    "producer": producer,
                    "creator": creator,
                    "detected_tool": ai_tool,
                }
            ))
            # Return early - AI generation is the most suspicious
            return flags

    # Check for highly suspicious producers (online converters)
    for suspicious in HIGHLY_SUSPICIOUS_PRODUCERS:
        if suspicious in combined:
            flags.append(Flag(
                severity="high",
                code="META_ONLINE_CONVERTER",
                message=f"Document was processed by online converter: {suspicious}",
                details={
                    "producer": producer,
                    "creator": creator,
                    "detected_tool": suspicious,
                }
            ))
            # Return early - no need to check for medium suspicious if high found
            return flags

    # Check for moderately suspicious producers
    for suspicious in SUSPICIOUS_PRODUCERS:
        if suspicious in combined:
            flags.append(Flag(
                severity="medium",
                code="META_SUSPICIOUS_PRODUCER",
                message=f"Document created with unusual software for invoices: {suspicious}",
                details={
                    "producer": producer,
                    "creator": creator,
                    "detected_tool": suspicious,
                }
            ))
            return flags

    return flags


def check_dates(
    creation_date: datetime | None,
    mod_date: datetime | None
) -> list[Flag]:
    """
    Check for suspicious date patterns in metadata.

    We check for:
    1. Future creation date (impossible without clock manipulation)
    2. Modification date much later than creation (document was edited)
    3. Modification date before creation (data corruption or manipulation)

    Args:
        creation_date: When the PDF was created
        mod_date: When the PDF was last modified

    Returns:
        List of Flag objects for any suspicious findings
    """
    # Everything below is compared against datetime.now(timezone.utc), so both
    # dates must be aware. parse_pdf_date already returns aware datetimes, but
    # tests (and other callers) may still pass naive ones. See src/dates.py.
    creation_date = to_aware_utc(creation_date)
    mod_date = to_aware_utc(mod_date)

    flags = []
    now = datetime.now(timezone.utc)

    # Check 1: Future creation date
    if creation_date and creation_date > now + timedelta(days=1):
        # Allow 1 day tolerance for timezone differences.
        # HIGH, not critical (2026-07 judge panel): the timestamp is a single
        # unauthenticated metadata field — scanners/MFPs with drifted or
        # never-configured clocks stamp far-future dates on genuine documents.
        flags.append(Flag(
            severity="high",
            code="META_FUTURE_CREATION_DATE",
            message="Document creation date is in the future",
            details={
                "creation_date": creation_date.isoformat(),
                "current_date": now.isoformat(),
            }
        ))

    # Check 2: Modification after creation
    # For official documents (attestations, certificates, invoices), the PDF
    # should be generated once and never modified. Any modification is suspicious.
    # A legitimate PDF generator creates and finalizes within 1-2 seconds max.
    if creation_date and mod_date:
        time_difference = mod_date - creation_date

        # Allow only 2 seconds tolerance - PDF generation is instant
        if time_difference > timedelta(seconds=2):
            # Severity graded by gap (2026-07 judge panel — was a flat
            # critical). ModDate/CreationDate are unauthenticated fields, and
            # legitimate pipelines rewrite ModDate: scan-then-view, sign,
            # flatten, optimize. A gap under 30 minutes is overwhelmingly a
            # viewer/scanner pipeline (medium); a longer gap means the file
            # really was reopened and edited later (high) — suspicious, but a
            # single uncorroborated metadata comparison is never critical.
            if time_difference > timedelta(days=1):
                days = time_difference.days
                message = f"Document was modified {days} days after creation"
            else:
                hours = int(time_difference.total_seconds() / 3600)
                minutes = int((time_difference.total_seconds() % 3600) / 60)
                seconds = int(time_difference.total_seconds())
                if hours > 0:
                    message = f"Document was modified {hours}h {minutes}min after creation"
                elif minutes > 0:
                    message = f"Document was modified {minutes} minute(s) after creation - possibly tampered"
                else:
                    message = f"Document was modified {seconds} second(s) after creation - possibly tampered"

            flags.append(Flag(
                severity="medium" if time_difference <= timedelta(minutes=30) else "high",
                code="META_DOCUMENT_MODIFIED",
                message=message,
                details={
                    "creation_date": creation_date.isoformat(),
                    "modification_date": mod_date.isoformat(),
                    "time_difference_hours": round(time_difference.total_seconds() / 3600, 2),
                    "explanation": "Official documents should never be modified after creation. "
                                   "This document was edited after it was originally generated.",
                }
            ))

    # Check 3: Modification before creation (impossible - data corrupted or faked)
    if creation_date and mod_date and mod_date < creation_date:
        flags.append(Flag(
            severity="high",
            code="META_IMPOSSIBLE_DATES",
            message="Modification date is before creation date (impossible)",
            details={
                "creation_date": creation_date.isoformat(),
                "mod_date": mod_date.isoformat(),
            }
        ))

    return flags


def check_missing_metadata(metadata_dict: dict) -> list[Flag]:
    """
    Check for suspiciously missing metadata.

    Professional invoices from billing systems usually have:
    - Producer (the software that made it)
    - Creation date

    If these are missing, it might indicate the metadata was stripped
    (to hide evidence of editing).

    Args:
        metadata_dict: Raw metadata dictionary from PyMuPDF

    Returns:
        List of Flag objects for any suspicious findings
    """
    flags = []

    # Check for completely empty metadata
    non_empty_fields = [k for k, v in metadata_dict.items() if v]

    if len(non_empty_fields) == 0:
        flags.append(Flag(
            severity="medium",
            code="META_NO_METADATA",
            message="Document has no metadata (possibly stripped)",
            details={"raw_metadata": metadata_dict}
        ))
    elif not metadata_dict.get("producer") and not metadata_dict.get("creator"):
        # Has some metadata but no producer/creator
        flags.append(Flag(
            severity="low",
            code="META_NO_PRODUCER",
            message="Document has no producer or creator information",
            details={"raw_metadata": metadata_dict}
        ))

    # A tool named itself, but no creation date. Keyed on Producer/Creator,
    # not "any field": PyMuPDF always fills "format", so a fully stripped file
    # would otherwise count as "present".
    #
    # Graded on ModDate (measured 2026-11-12 on every local sample):
    #   - ModDate present, CreationDate absent -> HIGH. The file was saved
    #     again and its creation date dropped: only Smallpdf ("Pdftools SDK")
    #     does this in the corpus.
    #   - neither date -> LOW (shown, near-weightless). Some libraries never
    #     write dates: Mustang Factur-X (8 legit invoices), a Chrome-printed
    #     notice. 9 legit vs 0 suspicious: anti-correlated, like
    #     META_NO_PRODUCER (see scoring.NON_EVIDENCE_CODES).
    names_tool = metadata_dict.get("producer") or metadata_dict.get("creator")
    if names_tool and not metadata_dict.get("creationDate"):
        rewritten = bool(metadata_dict.get("modDate"))
        flags.append(Flag(
            severity="high" if rewritten else "low",
            code="META_NO_CREATION_DATE",
            message=("Document has a modification date but its creation date "
                     "was removed" if rewritten else
                     "Document has no creation date"),
            details={
                "producer": metadata_dict.get("producer"),
                "mod_date": metadata_dict.get("modDate") or None,
                "explanation": "PDF software records when the file was created. "
                               "A file that keeps a modification date but lost "
                               "its creation date was rebuilt by another tool.",
            }
        ))

    return flags


# Characters a PDF date ever uses: "D:20240115143052+01'00'", "...Z".
_PDF_DATE_CHARS = re.compile(r"^(D:)?[0-9Z+\-' ]+$")


def _is_garbled_date(value: str) -> bool:
    """True when a metadata date is not a date in any format.

    A valid PDF date passes. So does a non-standard but real date
    ("2024-01-15T10:00:00", written by some libraries): dateutil reads it.
    Junk does not: "hello", "D:2026110fsdffsd1", a valid date plus letters.

    Examples:
        >>> _is_garbled_date("D:20240115143052+01'00'")
        False
        >>> _is_garbled_date("2024-01-15T10:00:00")
        False
        >>> _is_garbled_date("D:2026110fsdffsd1")
        True
    """
    if parse_pdf_date(value) is not None and _PDF_DATE_CHARS.match(value):
        return False
    try:
        date_parser.parse(value.removeprefix("D:"))
        return False
    except (ValueError, OverflowError):
        return True


def check_malformed_dates(metadata_dict: dict) -> list[Flag]:
    """Flag a creation or modification date that is not a date.

    Software always writes a real date. Junk there means the metadata was
    edited by hand, and it also dodged the date checks: an unreadable
    CreationDate is neither "missing" nor "older than ModDate". User rule
    2026-11-12; 0 of 205 corpus files have one (all use the standard form).
    """
    flags = []
    for key, label in (("creationDate", "creation"), ("modDate", "modification")):
        value = (metadata_dict.get(key) or "").strip()
        if value and _is_garbled_date(value):
            flags.append(Flag(
                severity="high",
                code="META_MALFORMED_DATE",
                message=f"The {label} date in the metadata is not a date: {value}",
                details={"field": key, "value": value},
            ))
    return flags


